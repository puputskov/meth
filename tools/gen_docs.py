#!/usr/bin/env python3
"""Compiles the pages of data/docs/ into the program.

Usage: python tools/gen_docs.py [--check]

Reads data/docs/*.md and writes source/meth/docs/pages_data.c: a table of the
pages (the file name without .md is the id), each as C string literals, one
literal per line of the page. The same is done for data/examples/*.meth, written to
source/meth/docs/examples_data.c, and for data/snippets/*.meth (snippets_data.c). With --check nothing is written; the exit
code is 1 when a file on disk is not what would be written (the tests and the
build use it to find pages that were changed without running this tool).
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "data", "docs")
OUT = os.path.join(ROOT, "source", "meth", "docs", "pages_data.c")
EXAMPLES = os.path.join(ROOT, "data", "examples")
EXAMPLES_OUT = os.path.join(ROOT, "source", "meth", "docs", "examples_data.c")
SNIPPETS = os.path.join(ROOT, "data", "snippets")
SNIPPETS_OUT = os.path.join(ROOT, "source", "meth", "docs", "snippets_data.c")
STDLIB = os.path.join(ROOT, "data", "stdlib")
STDLIB_OUT = os.path.join(ROOT, "source", "meth", "docs", "stdlib_data.c")
TEXTS = os.path.join(ROOT, "data", "texts")
TEXTS_OUT = os.path.join(ROOT, "source", "meth", "texts", "catalog_data.c")

# A literal line is a tab, quotes and at most this many escaped characters:
# four columns for the tab, two quotes and the semicolon of the last line.
MAX_ESCAPED = 70


def escape(chunk):
    out = []
    for b in chunk.encode("utf-8"):
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif 32 <= b < 127:
            out.append(c)
        else:
            # octal escapes end after three digits, so a digit that follows
            # is never taken for part of them
            out.append("\\%03o" % b)
    return "".join(out)


def pieces(line):
    """The line cut into chunks whose escaped form fits one literal."""
    chunks = []
    current = ""
    for ch in line:
        if len(escape(current + ch)) > MAX_ESCAPED:
            chunks.append(current)
            current = ""
        current += ch
    chunks.append(current)
    return chunks


def literals(text):
    lines = text.replace("\r\n", "\n").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    out = []
    for i, line in enumerate(lines):
        chunks = pieces(line)
        for k, chunk in enumerate(chunks):
            tail = "\\n" if k == len(chunks) - 1 else ""
            out.append('\t"%s%s"' % (escape(chunk), tail))
    return out


def generate_table(folder, ext, comment, header, prefix, kind="MlDocSource", base="docs", extra=()):
    """The C source of a table of the files of folder with the extension.

    The table is `ml_<prefix>_sources` with `ml_<prefix>_source_count`."""
    names = sorted(f[: -len(ext)] for f in os.listdir(folder) if f.endswith(ext))
    # more folders: (folder, extension, prefix of the names), after the first
    files = {name: os.path.join(folder, name + ext) for name in names}
    for xfolder, xext, xprefix in extra:
        for n in sorted(f[: -len(xext)] for f in os.listdir(xfolder) if f.endswith(xext)):
            names.append(xprefix + n)
            files[xprefix + n] = os.path.join(xfolder, n + xext)
    parts = [
        "/* Generated by tools/gen_docs.py from %s, do not edit. */" % comment,
        "",
        "#include <meth/%s/%s.h>" % (base, header),
        "",
    ]
    for name in names:
        with open(files[name], encoding="utf-8") as f:
            text = f.read()
        ident = name.replace("-", "_").replace("/", "_")
        parts.append("static const char text_%s [] =" % ident)
        body = literals(text)
        body[-1] += ";"
        parts.extend(body)
        parts.append("")
    parts.append("const %s ml_%s_sources [] =" % (kind, prefix))
    parts.append("{")
    rows = []
    for name in names:
        ident = name.replace("-", "_").replace("/", "_")
        row = '\t{ .name = "%s", .text = text_%s }' % (name, ident)
        if len(row) + 3 > 80:
            # a tab counts as 4 columns, and the comma: break the row
            row = '\t{\n\t\t.name = "%s",\n\t\t.text = text_%s\n\t}' % (name, ident)
        rows.append(row)
    parts.append(",\n".join(rows))
    parts.append("};")
    parts.append("")
    parts.append(
        "const uint64_t ml_%s_source_count = ml_count (ml_%s_sources);"
        % (prefix, prefix)
    )
    return "\n".join(parts) + "\n"


def generate():
    return generate_table("%s" % DOCS, ".md", "data/docs/*.md", "docs", "doc")


def generate_snippets():
    return generate_table(SNIPPETS, ".meth", "data/snippets/*.meth", "snippets", "snippet")


def generate_texts():
    # the English texts, then the lessons of the tutorial, one file each
    return generate_table(
        TEXTS, ".mltext", "texts and lessons", "texts", "catalog",
        "MlCatalogSource", "texts", extra=[(os.path.join(ROOT, "data", "lessons", "en"), ".mltext", "lessons/en/")]
    )


def generate_stdlib():
    return generate_table(STDLIB, ".meth", "data/stdlib/*.meth", "stdlib", "stdlib")


def generate_examples():
    return generate_table(EXAMPLES, ".meth", "data/examples/*.meth", "examples", "example")


def differs(path, text):
    try:
        with open(path, encoding="utf-8", newline="") as f:
            have = f.read().replace("\r\n", "\n")
    except FileNotFoundError:
        have = ""
    return have != text


def main():
    outputs = [
        (OUT, generate()),
        (EXAMPLES_OUT, generate_examples()),
        (SNIPPETS_OUT, generate_snippets()),
        (STDLIB_OUT, generate_stdlib()),
        (TEXTS_OUT, generate_texts()),
    ]
    if "--check" in sys.argv:
        stale = [p for p, text in outputs if differs(p, text)]
        for p in stale:
            print(os.path.basename(p), "is not up to date: run python tools/gen_docs.py")
        return 1 if stale else 0
    for path, text in outputs:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text.replace("\n", "\r\n"))
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
