#!/usr/bin/env python3
"""Compiles the pages of docs/ into the program.

Usage: python tools/gen_docs.py [--check]

Reads docs/*.md and writes source/matlog/docs/pages_data.c: a table of the
pages (the file name without .md is the id), each as C string literals, one
literal per line of the page. With --check nothing is written; the exit code
is 1 when the file on disk is not what would be written (the tests and the
build use it to find pages that were changed without running this tool).
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
OUT = os.path.join(ROOT, "source", "matlog", "docs", "pages_data.c")

# A literal line is a tab, quotes and at most this many escaped characters:
# four columns for the tab, two quotes and the semicolon of the last line.
MAX_ESCAPED = 70


def escape(chunk):
    out = []
    for b in chunk.encode("utf-8"):
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\t":
            out.append("\\t")
        elif 32 <= b < 127:
            out.append(c)
        else:
            # octal escapes end after three digits, so a digit that follows
            # is never taken for part of them
            out.append("\\%03o" % b)
    return "".join(out)


def pieces(line):
    """The line cut into chunks whose escaped form fits one literal."""
    chunks = []
    current = ""
    for ch in line:
        if len(escape(current + ch)) > MAX_ESCAPED:
            chunks.append(current)
            current = ""
        current += ch
    chunks.append(current)
    return chunks


def literals(text):
    lines = text.replace("\r\n", "\n").split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    out = []
    for i, line in enumerate(lines):
        chunks = pieces(line)
        for k, chunk in enumerate(chunks):
            tail = "\\n" if k == len(chunks) - 1 else ""
            out.append('\t"%s%s"' % (escape(chunk), tail))
    return out


def generate():
    names = sorted(f[:-3] for f in os.listdir(DOCS) if f.endswith(".md"))
    parts = [
        "/* Generated by tools/gen_docs.py from docs/*.md, do not edit. */",
        "",
        "#include <matlog/docs/docs.h>",
        "",
    ]
    for name in names:
        with open(os.path.join(DOCS, name + ".md"), encoding="utf-8") as f:
            text = f.read()
        ident = name.replace("-", "_")
        parts.append("static const char text_%s [] =" % ident)
        body = literals(text)
        body[-1] += ";"
        parts.extend(body)
        parts.append("")
    parts.append("const MlDocSource ml_doc_sources [] =")
    parts.append("{")
    rows = []
    for name in names:
        rows.append(
            '\t{ .name = "%s", .text = text_%s }' % (name, name.replace("-", "_"))
        )
    parts.append(",\n".join(rows))
    parts.append("};")
    parts.append("")
    parts.append("const uint64_t ml_doc_source_count = ml_count (ml_doc_sources);")
    return "\n".join(parts) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8", newline="") as f:
                have = f.read().replace("\r\n", "\n")
        except FileNotFoundError:
            have = ""
        if have != text:
            print("pages_data.c is not up to date: run python tools/gen_docs.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text.replace("\n", "\r\n"))
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
